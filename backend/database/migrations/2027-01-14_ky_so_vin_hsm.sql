/* ============================================================================
 * 2027-01-14_ky_so_vin_hsm
 * ----------------------------------------------------------------------------
 *   Ký số từ xa qua VIN-HSM (modules/signing/). Khóa ký nằm trong HSM của nhà
 *   cung cấp; mỗi tài khoản dịch vụ (API key + secret) gắn với 1 chứng thư số.
 *
 *   signing_accounts — tài khoản ký
 *     kind                 organization (chứng thư của bệnh viện, dùng chung)
 *                          | personal (chứng thư của 1 người, user_id bắt buộc)
 *     region               vùng máy chủ VIN-HSM: host = sign-<region>.vin-hsm.com (vd hn10)
 *     api_key              API key nhà cung cấp cấp
 *     secret_enc           secret đã mã hóa AES-256-GCM (utils/secretBox.js) — KHÔNG lưu rõ
 *     cert_*               thông tin chứng thư đọc từ VIN-HSM ở lần kiểm tra gần nhất
 *     use_for_certificates tài khoản tổ chức dùng ký giấy chứng nhận CME (tối đa 1 tài khoản)
 *     personal: mỗi người tối đa 1 tài khoản
 *
 *   signing_logs — nhật ký mỗi lần gọi ký (thành công lẫn lỗi). Không lưu nội dung
 *   file, chỉ SHA-256 trước/sau để đối chiếu.
 *     doc_type   seminar_certificate | course_certificate | practice_document
 *                | registration_document | topic_approval | test
 *     doc_ref    mã đối tượng (mã hội nghị, mã đề tài, mã đăng ký...)
 *     status     ok | error
 *
 * Chạy trong 1 transaction. Idempotent.
 * ==========================================================================*/

CREATE TABLE IF NOT EXISTS signing_accounts (
	id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	label varchar(200) COLLATE "vi-VN-x-icu" NOT NULL,
	kind varchar(15) NOT NULL,
	user_id varchar(20),
	provider varchar(20) DEFAULT 'vin_hsm' NOT NULL,
	region varchar(20) NOT NULL,
	api_key varchar(200) NOT NULL,
	secret_enc text NOT NULL,
	cert_subject varchar(500),
	cert_issuer varchar(500),
	cert_serial varchar(100),
	cert_valid_from timestamp(0),
	cert_valid_to timestamp(0),
	checked_at timestamp(3),
	last_error varchar(500),
	use_for_certificates boolean DEFAULT false NOT NULL,
	is_active boolean DEFAULT true NOT NULL,
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	created_by varchar(20),
	updated_at timestamp(3),
	updated_by varchar(20),
	CONSTRAINT signing_accounts_pkey PRIMARY KEY (id)
);

ALTER TABLE signing_accounts DROP CONSTRAINT IF EXISTS chk_signacc_kind;
ALTER TABLE signing_accounts ADD CONSTRAINT chk_signacc_kind CHECK (
	(kind = 'organization' AND user_id IS NULL)
	OR (kind = 'personal' AND user_id IS NOT NULL)
);

ALTER TABLE signing_accounts DROP CONSTRAINT IF EXISTS chk_signacc_cert_use;
ALTER TABLE signing_accounts ADD CONSTRAINT chk_signacc_cert_use
	CHECK (NOT use_for_certificates OR kind = 'organization');

ALTER TABLE signing_accounts DROP CONSTRAINT IF EXISTS chk_signacc_region;
ALTER TABLE signing_accounts ADD CONSTRAINT chk_signacc_region CHECK (region ~ '^[a-z0-9]{1,20}$');

ALTER TABLE signing_accounts DROP CONSTRAINT IF EXISTS fk_signacc_user;
ALTER TABLE signing_accounts ADD CONSTRAINT fk_signacc_user
	FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;

CREATE UNIQUE INDEX IF NOT EXISTS uq_signacc_personal_user ON signing_accounts (user_id)
	WHERE kind = 'personal';
CREATE UNIQUE INDEX IF NOT EXISTS uq_signacc_cert_default ON signing_accounts (use_for_certificates)
	WHERE use_for_certificates;

CREATE TABLE IF NOT EXISTS signing_logs (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	account_id integer,
	actor_id varchar(20),
	doc_type varchar(30) NOT NULL,
	doc_ref varchar(60),
	endpoint varchar(100) NOT NULL,
	input_sha256 char(64),
	output_sha256 char(64),
	cert_serial varchar(100),
	status varchar(10) NOT NULL,
	error_code integer,
	error_message varchar(500),
	duration_ms integer,
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	CONSTRAINT signing_logs_pkey PRIMARY KEY (id)
);

ALTER TABLE signing_logs DROP CONSTRAINT IF EXISTS chk_signlog_status;
ALTER TABLE signing_logs ADD CONSTRAINT chk_signlog_status CHECK (status IN ('ok', 'error'));

-- Xóa tài khoản không xóa nhật ký (còn tra được ai đã ký bằng chứng thư nào)
ALTER TABLE signing_logs DROP CONSTRAINT IF EXISTS fk_signlog_account;
ALTER TABLE signing_logs ADD CONSTRAINT fk_signlog_account
	FOREIGN KEY (account_id) REFERENCES signing_accounts (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS ix_signlog_created ON signing_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_signlog_doc ON signing_logs (doc_type, doc_ref);
CREATE INDEX IF NOT EXISTS ix_signlog_account ON signing_logs (account_id) WHERE account_id IS NOT NULL;
