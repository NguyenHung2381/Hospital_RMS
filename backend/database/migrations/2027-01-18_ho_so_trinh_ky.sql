/* ============================================================================
 * 2027-01-18_ho_so_trinh_ky
 * ----------------------------------------------------------------------------
 *   Luồng trình ký văn bản (modules/signing/requests/): người tạo gửi 1 hồ sơ gồm 1..n văn
 *   bản PDF cho nhiều người ký theo các BƯỚC nối tiếp; trong 1 bước nhiều người ký song song
 *   (mode all = tất cả phải ký, any = 1 người ký là đủ). Mỗi lần ký = ký số VIN-HSM bằng chứng
 *   thư cá nhân lên MỌI văn bản của hồ sơ (ký nối tiếp — chữ ký trước vẫn hợp lệ).
 *   Từ chối ⇒ dừng cả hồ sơ, trả người tạo. File lưu ở uploads/sign-requests/<id>/ (mỗi lần ký
 *   1 phiên bản mới, không ghi đè) — chỉ tải qua API có kiểm quyền, không qua link /uploads.
 *
 *   sign_requests            hồ sơ: status in_progress | completed | rejected | cancelled,
 *                            current_step = bước đang chờ ký
 *   sign_request_documents   văn bản: current_version / current_path = bản mới nhất
 *   sign_request_versions    lịch sử từng bản (v1 = bản gốc người tạo tải lên)
 *   sign_request_steps       bước: step_no 1..n, mode all | any
 *   sign_request_signers     người ký trong bước: status waiting (chưa tới bước) | pending
 *                            (đang chờ ký) | signed | rejected | skipped (bước "any" đã có
 *                            người ký)
 *   sign_request_fields      vị trí khung chữ ký đặt sẵn cho (văn bản, người ký): pt, gốc
 *                            dưới-trái trang. Không có ⇒ người ký tự đặt khi ký.
 *   sign_request_events      nhật ký hồ sơ (tạo, ký, từ chối, hủy, hoàn tất)
 *
 * Chạy trong 1 transaction. Idempotent.
 * ==========================================================================*/

CREATE TABLE IF NOT EXISTS sign_requests (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	title varchar(300) COLLATE "vi-VN-x-icu" NOT NULL,
	message text,
	status varchar(15) DEFAULT 'in_progress' NOT NULL,
	current_step integer DEFAULT 1 NOT NULL,
	due_date date,
	completed_at timestamp(3),
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	created_by varchar(20) NOT NULL,
	updated_at timestamp(3),
	updated_by varchar(20),
	CONSTRAINT sign_requests_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_requests DROP CONSTRAINT IF EXISTS chk_signreq_status;
ALTER TABLE sign_requests ADD CONSTRAINT chk_signreq_status
	CHECK (status IN ('in_progress', 'completed', 'rejected', 'cancelled'));
ALTER TABLE sign_requests DROP CONSTRAINT IF EXISTS fk_signreq_creator;
ALTER TABLE sign_requests ADD CONSTRAINT fk_signreq_creator
	FOREIGN KEY (created_by) REFERENCES users (id);
CREATE INDEX IF NOT EXISTS ix_signreq_creator ON sign_requests (created_by, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_signreq_status ON sign_requests (status, created_at DESC);

CREATE TABLE IF NOT EXISTS sign_request_documents (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	request_id bigint NOT NULL,
	sort_order integer DEFAULT 0 NOT NULL,
	file_name varchar(255) COLLATE "vi-VN-x-icu" NOT NULL,
	page_count integer,
	current_version integer DEFAULT 1 NOT NULL,
	current_path varchar(500) NOT NULL,
	current_sha256 char(64) NOT NULL,
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	CONSTRAINT sign_request_documents_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_request_documents DROP CONSTRAINT IF EXISTS fk_signreqdoc_request;
ALTER TABLE sign_request_documents ADD CONSTRAINT fk_signreqdoc_request
	FOREIGN KEY (request_id) REFERENCES sign_requests (id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS ix_signreqdoc_request ON sign_request_documents (request_id, sort_order);

CREATE TABLE IF NOT EXISTS sign_request_versions (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	document_id bigint NOT NULL,
	version integer NOT NULL,
	path varchar(500) NOT NULL,
	sha256 char(64) NOT NULL,
	size_bytes integer NOT NULL,
	signer_user_id varchar(20),
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	CONSTRAINT sign_request_versions_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_request_versions DROP CONSTRAINT IF EXISTS fk_signreqver_document;
ALTER TABLE sign_request_versions ADD CONSTRAINT fk_signreqver_document
	FOREIGN KEY (document_id) REFERENCES sign_request_documents (id) ON DELETE CASCADE;
ALTER TABLE sign_request_versions DROP CONSTRAINT IF EXISTS uq_signreqver_doc_version;
ALTER TABLE sign_request_versions ADD CONSTRAINT uq_signreqver_doc_version UNIQUE (document_id, version);

CREATE TABLE IF NOT EXISTS sign_request_steps (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	request_id bigint NOT NULL,
	step_no integer NOT NULL,
	mode varchar(5) DEFAULT 'all' NOT NULL,
	CONSTRAINT sign_request_steps_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_request_steps DROP CONSTRAINT IF EXISTS fk_signreqstep_request;
ALTER TABLE sign_request_steps ADD CONSTRAINT fk_signreqstep_request
	FOREIGN KEY (request_id) REFERENCES sign_requests (id) ON DELETE CASCADE;
ALTER TABLE sign_request_steps DROP CONSTRAINT IF EXISTS uq_signreqstep_no;
ALTER TABLE sign_request_steps ADD CONSTRAINT uq_signreqstep_no UNIQUE (request_id, step_no);
ALTER TABLE sign_request_steps DROP CONSTRAINT IF EXISTS chk_signreqstep_mode;
ALTER TABLE sign_request_steps ADD CONSTRAINT chk_signreqstep_mode CHECK (mode IN ('all', 'any'));

CREATE TABLE IF NOT EXISTS sign_request_signers (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	request_id bigint NOT NULL,
	step_no integer NOT NULL,
	user_id varchar(20) NOT NULL,
	status varchar(10) DEFAULT 'waiting' NOT NULL,
	acted_at timestamp(3),
	note varchar(1000) COLLATE "vi-VN-x-icu",
	CONSTRAINT sign_request_signers_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_request_signers DROP CONSTRAINT IF EXISTS fk_signreqsigner_request;
ALTER TABLE sign_request_signers ADD CONSTRAINT fk_signreqsigner_request
	FOREIGN KEY (request_id) REFERENCES sign_requests (id) ON DELETE CASCADE;
ALTER TABLE sign_request_signers DROP CONSTRAINT IF EXISTS fk_signreqsigner_user;
ALTER TABLE sign_request_signers ADD CONSTRAINT fk_signreqsigner_user
	FOREIGN KEY (user_id) REFERENCES users (id);
ALTER TABLE sign_request_signers DROP CONSTRAINT IF EXISTS chk_signreqsigner_status;
ALTER TABLE sign_request_signers ADD CONSTRAINT chk_signreqsigner_status
	CHECK (status IN ('waiting', 'pending', 'signed', 'rejected', 'skipped'));
-- Một người chỉ xuất hiện 1 lần trong 1 hồ sơ
ALTER TABLE sign_request_signers DROP CONSTRAINT IF EXISTS uq_signreqsigner_user;
ALTER TABLE sign_request_signers ADD CONSTRAINT uq_signreqsigner_user UNIQUE (request_id, user_id);
-- Hộp thư "Cần tôi ký"
CREATE INDEX IF NOT EXISTS ix_signreqsigner_user_status ON sign_request_signers (user_id, status);

CREATE TABLE IF NOT EXISTS sign_request_fields (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	request_id bigint NOT NULL,
	document_id bigint NOT NULL,
	signer_id bigint NOT NULL,
	page integer NOT NULL,
	x numeric(9, 2) NOT NULL,
	y numeric(9, 2) NOT NULL,
	width numeric(9, 2) NOT NULL,
	height numeric(9, 2) NOT NULL,
	CONSTRAINT sign_request_fields_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_request_fields DROP CONSTRAINT IF EXISTS fk_signreqfield_request;
ALTER TABLE sign_request_fields ADD CONSTRAINT fk_signreqfield_request
	FOREIGN KEY (request_id) REFERENCES sign_requests (id) ON DELETE CASCADE;
ALTER TABLE sign_request_fields DROP CONSTRAINT IF EXISTS fk_signreqfield_document;
ALTER TABLE sign_request_fields ADD CONSTRAINT fk_signreqfield_document
	FOREIGN KEY (document_id) REFERENCES sign_request_documents (id) ON DELETE CASCADE;
ALTER TABLE sign_request_fields DROP CONSTRAINT IF EXISTS fk_signreqfield_signer;
ALTER TABLE sign_request_fields ADD CONSTRAINT fk_signreqfield_signer
	FOREIGN KEY (signer_id) REFERENCES sign_request_signers (id) ON DELETE CASCADE;
-- Mỗi người 1 khung trên 1 văn bản
ALTER TABLE sign_request_fields DROP CONSTRAINT IF EXISTS uq_signreqfield_doc_signer;
ALTER TABLE sign_request_fields ADD CONSTRAINT uq_signreqfield_doc_signer UNIQUE (document_id, signer_id);

CREATE TABLE IF NOT EXISTS sign_request_events (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	request_id bigint NOT NULL,
	actor_id varchar(20),
	action varchar(20) NOT NULL,
	note varchar(1000) COLLATE "vi-VN-x-icu",
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	CONSTRAINT sign_request_events_pkey PRIMARY KEY (id)
);
ALTER TABLE sign_request_events DROP CONSTRAINT IF EXISTS fk_signreqevent_request;
ALTER TABLE sign_request_events ADD CONSTRAINT fk_signreqevent_request
	FOREIGN KEY (request_id) REFERENCES sign_requests (id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS ix_signreqevent_request ON sign_request_events (request_id, created_at);
