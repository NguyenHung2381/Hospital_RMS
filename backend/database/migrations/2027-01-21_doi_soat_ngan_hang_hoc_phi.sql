 * ----------------------------------------------------------------------------
 *   Tự đối soát học phí qua API ngân hàng (modules/training/tuition/bank/).
 *
 *   Ngân hàng (hoặc dịch vụ trung gian) báo giao dịch tiền VÀO tài khoản nhận học phí
 *   qua webhook /api/v1/bank-webhooks/:provider. Mỗi giao dịch ghi 1 dòng ở đây rồi
 *   dò nội dung chuyển khoản "HP <mã ghi danh>" (tuitionService.transferContent):
 *     matched    khớp lượt ghi danh, đủ điều kiện ⇒ đã tạo / xác nhận khoản nộp
 *                (tuition_payments, cấp phiếu thu) — payment_id trỏ tới khoản đó
 *     unmatched  chưa tự khớp được (reason cho biết vì sao) ⇒ phòng Đào tạo xử lý tay:
 *                gán cho 1 lượt ghi danh hoặc bỏ qua
 *     ignored    đã xem, không phải tiền học phí (hoặc đã xử lý ngoài hệ thống)
 *
 *   (provider, external_id) duy nhất ⇒ ngân hàng gửi lại cùng giao dịch không bị ghi 2 lần.
 *
 * Chạy trong 1 transaction. Idempotent.
 * ==========================================================================*/

CREATE TABLE IF NOT EXISTS tuition_bank_transactions (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	provider varchar(30) NOT NULL,
	external_id varchar(100) NOT NULL,
	account_no varchar(30),
	amount numeric(18,0) NOT NULL,
	content varchar(500) COLLATE "vi-VN-x-icu",
	txn_time timestamp(3),
	status varchar(10) DEFAULT 'unmatched' NOT NULL,
	reason varchar(20),
	enrollment_id varchar(20),
	payment_id varchar(20),
	note varchar(500) COLLATE "vi-VN-x-icu",
	raw jsonb,
	received_at timestamp(3) DEFAULT LOCALTIMESTAMP NOT NULL,
	handled_by varchar(20),
	handled_at timestamp(3),
	CONSTRAINT tuition_bank_transactions_pkey PRIMARY KEY (id)
);

ALTER TABLE tuition_bank_transactions DROP CONSTRAINT IF EXISTS uq_tuibank_external;
ALTER TABLE tuition_bank_transactions ADD CONSTRAINT uq_tuibank_external UNIQUE (provider, external_id);
ALTER TABLE tuition_bank_transactions DROP CONSTRAINT IF EXISTS chk_tuibank_amount;
ALTER TABLE tuition_bank_transactions ADD CONSTRAINT chk_tuibank_amount CHECK (amount > 0);
ALTER TABLE tuition_bank_transactions DROP CONSTRAINT IF EXISTS chk_tuibank_status;
ALTER TABLE tuition_bank_transactions ADD CONSTRAINT chk_tuibank_status
	CHECK (status IN ('unmatched', 'matched', 'ignored'));
-- Đã khớp thì phải trỏ tới khoản nộp
ALTER TABLE tuition_bank_transactions DROP CONSTRAINT IF EXISTS chk_tuibank_matched;
ALTER TABLE tuition_bank_transactions ADD CONSTRAINT chk_tuibank_matched
	CHECK (status <> 'matched' OR payment_id IS NOT NULL);
ALTER TABLE tuition_bank_transactions DROP CONSTRAINT IF EXISTS fk_tuibank_enrollment;
ALTER TABLE tuition_bank_transactions ADD CONSTRAINT fk_tuibank_enrollment
	FOREIGN KEY (enrollment_id) REFERENCES course_enrollments (id) ON DELETE SET NULL;
ALTER TABLE tuition_bank_transactions DROP CONSTRAINT IF EXISTS fk_tuibank_payment;
ALTER TABLE tuition_bank_transactions ADD CONSTRAINT fk_tuibank_payment
	FOREIGN KEY (payment_id) REFERENCES tuition_payments (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS ix_tuibank_received ON tuition_bank_transactions (received_at DESC);
-- Hàng chờ xử lý tay (việc cần làm của phòng Đào tạo)
CREATE INDEX IF NOT EXISTS ix_tuibank_unmatched ON tuition_bank_transactions (received_at)
	WHERE status = 'unmatched';
-- Một khoản nộp chỉ gắn với tối đa 1 giao dịch ngân hàng
CREATE UNIQUE INDEX IF NOT EXISTS uq_tuibank_payment ON tuition_bank_transactions (payment_id)
	WHERE payment_id IS NOT NULL;

COMMENT ON TABLE tuition_bank_transactions IS
	'Giao dịch tiền vào tài khoản nhận học phí do ngân hàng báo qua webhook — tự đối soát theo nội dung "HP <mã ghi danh>"';
COMMENT ON COLUMN tuition_bank_transactions.reason IS
	'Vì sao chưa tự khớp: no_code, ambiguous, not_found, not_approved, no_fee, overpay, auto_off, wrong_account, error';
