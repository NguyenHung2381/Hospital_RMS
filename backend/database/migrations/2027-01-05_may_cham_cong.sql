/* ============================================================================
 * 2027-01-05_may_cham_cong
 * ----------------------------------------------------------------------------
 *   Máy chấm công vân tay (giao thức ADMS / "iclock" — máy tự mở kết nối lên server,
 *   server không cần vào được mạng của máy). modules/attendanceDevices/.
 *
 *   attendance_devices          — máy, nhận diện bằng số serial (SN). Máy lạ tự gửi tới
 *                                 được ghi 'pending', chỉ nhận dữ liệu khi quản trị duyệt.
 *   attendance_punches          — lượt chấm thô từ máy + kết quả ghép vào buổi học.
 *                                 UNIQUE (máy, PIN, giờ chấm): máy gửi lại không nhân đôi.
 *   attendance_device_commands  — hàng đợi lệnh server gửi xuống máy (máy hỏi qua
 *                                 /iclock/getrequest, báo kết quả qua /iclock/devicecmd).
 *   attendance_device_users     — học viên server đã gửi xuống từng máy (để so khớp
 *                                 "cần có" ↔ "đang có", dọn khi khóa học kết thúc).
 *   trainee_fingerprints        — mẫu vân tay (đồng bộ giữa các máy). template_enc mã hóa
 *                                 AES-GCM (utils/secretBox) — dữ liệu sinh trắc học, không
 *                                 API nào trả ra; xóa khi học viên được dọn khỏi mọi máy.
 *
 *   Giờ lưu theo UTC (như attendance.checked_in_at) — FE hiển thị bằng formatDateTimeVN.
 *   attendance.method thêm 'device'.
 *
 * Chạy trong 1 transaction. Idempotent.
 * ==========================================================================*/

CREATE TABLE IF NOT EXISTS attendance_devices (
	id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	serial_no varchar(40) NOT NULL,
	name varchar(150) COLLATE "vi-VN-x-icu",
	location varchar(255),
	status varchar(10) DEFAULT 'pending' NOT NULL,
	name_ascii boolean DEFAULT false NOT NULL,
	push_version varchar(20),
	firmware varchar(100),
	fp_algorithm varchar(20),
	device_info text,
	last_seen_at timestamp(3),
	last_ip varchar(45),
	attlog_stamp varchar(20),
	operlog_stamp varchar(20),
	user_count integer,
	fp_count integer,
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	created_by varchar(20),
	updated_at timestamp(3),
	updated_by varchar(20),
	CONSTRAINT attendance_devices_pkey PRIMARY KEY (id)
);

ALTER TABLE attendance_devices DROP CONSTRAINT IF EXISTS uq_attdev_serial;
ALTER TABLE attendance_devices ADD CONSTRAINT uq_attdev_serial UNIQUE (serial_no);
ALTER TABLE attendance_devices DROP CONSTRAINT IF EXISTS chk_attdev_status;
ALTER TABLE attendance_devices ADD CONSTRAINT chk_attdev_status
	CHECK (status IN ('pending', 'active', 'disabled'));

CREATE TABLE IF NOT EXISTS attendance_punches (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	device_id integer NOT NULL,
	pin varchar(24) NOT NULL,
	punched_at timestamp(0) NOT NULL,
	verify_mode smallint,
	in_out smallint,
	trainee_id varchar(20),
	session_id varchar(20),
	match_status varchar(12) DEFAULT 'pending' NOT NULL,
	matched_at timestamp(3),
	received_at timestamp(3) DEFAULT (now() AT TIME ZONE 'UTC') NOT NULL,
	CONSTRAINT attendance_punches_pkey PRIMARY KEY (id)
);

ALTER TABLE attendance_punches DROP CONSTRAINT IF EXISTS uq_attpunch_device_pin_time;
ALTER TABLE attendance_punches ADD CONSTRAINT uq_attpunch_device_pin_time
	UNIQUE (device_id, pin, punched_at);
ALTER TABLE attendance_punches DROP CONSTRAINT IF EXISTS chk_attpunch_match_status;
ALTER TABLE attendance_punches ADD CONSTRAINT chk_attpunch_match_status
	CHECK (match_status IN ('pending', 'matched', 'no_trainee', 'no_session', 'kept_manual', 'locked'));
ALTER TABLE attendance_punches DROP CONSTRAINT IF EXISTS fk_attpunch_device;
ALTER TABLE attendance_punches ADD CONSTRAINT fk_attpunch_device
	FOREIGN KEY (device_id) REFERENCES attendance_devices (id) ON DELETE CASCADE;
-- Buổi học bị xóa thì lượt chấm giữ lại (về chưa ghép), không xóa theo
ALTER TABLE attendance_punches DROP CONSTRAINT IF EXISTS fk_attpunch_session;
ALTER TABLE attendance_punches ADD CONSTRAINT fk_attpunch_session
	FOREIGN KEY (session_id) REFERENCES class_sessions (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS ix_attpunch_time ON attendance_punches (punched_at);
CREATE INDEX IF NOT EXISTS ix_attpunch_unmatched ON attendance_punches (match_status, punched_at)
	WHERE match_status IN ('pending', 'no_trainee', 'no_session');
CREATE INDEX IF NOT EXISTS ix_attpunch_trainee ON attendance_punches (trainee_id);

CREATE TABLE IF NOT EXISTS attendance_device_commands (
	id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	device_id integer NOT NULL,
	kind varchar(20) NOT NULL,
	trainee_id varchar(20),
	command text NOT NULL,
	status varchar(10) DEFAULT 'pending' NOT NULL,
	return_code integer,
	attempts smallint DEFAULT 0 NOT NULL,
	sent_at timestamp(3),
	done_at timestamp(3),
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'UTC') NOT NULL,
	created_by varchar(20),
	CONSTRAINT attendance_device_commands_pkey PRIMARY KEY (id)
);

ALTER TABLE attendance_device_commands DROP CONSTRAINT IF EXISTS chk_attcmd_status;
ALTER TABLE attendance_device_commands ADD CONSTRAINT chk_attcmd_status
	CHECK (status IN ('pending', 'sent', 'done', 'failed', 'cancelled'));
ALTER TABLE attendance_device_commands DROP CONSTRAINT IF EXISTS chk_attcmd_kind;
ALTER TABLE attendance_device_commands ADD CONSTRAINT chk_attcmd_kind
	CHECK (kind IN ('user_upsert', 'user_delete', 'fp_upsert', 'query_attlog', 'info', 'other'));
ALTER TABLE attendance_device_commands DROP CONSTRAINT IF EXISTS fk_attcmd_device;
ALTER TABLE attendance_device_commands ADD CONSTRAINT fk_attcmd_device
	FOREIGN KEY (device_id) REFERENCES attendance_devices (id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS ix_attcmd_device_status ON attendance_device_commands (device_id, status, id);

CREATE TABLE IF NOT EXISTS attendance_device_users (
	device_id integer NOT NULL,
	trainee_id varchar(20) NOT NULL,
	pin varchar(24) NOT NULL,
	name_sent varchar(50),
	fp_hashes text,
	synced_at timestamp(3),
	CONSTRAINT attendance_device_users_pkey PRIMARY KEY (device_id, trainee_id)
);

ALTER TABLE attendance_device_users DROP CONSTRAINT IF EXISTS fk_attdevuser_device;
ALTER TABLE attendance_device_users ADD CONSTRAINT fk_attdevuser_device
	FOREIGN KEY (device_id) REFERENCES attendance_devices (id) ON DELETE CASCADE;
ALTER TABLE attendance_device_users DROP CONSTRAINT IF EXISTS fk_attdevuser_trainee;
ALTER TABLE attendance_device_users ADD CONSTRAINT fk_attdevuser_trainee
	FOREIGN KEY (trainee_id) REFERENCES trainees (id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS trainee_fingerprints (
	trainee_id varchar(20) NOT NULL,
	finger_index smallint NOT NULL,
	template_enc text NOT NULL,
	template_hash varchar(64) NOT NULL,
	size integer,
	valid smallint DEFAULT 1 NOT NULL,
	algo_version varchar(20),
	source_device_id integer,
	created_at timestamp(3) DEFAULT (now() AT TIME ZONE 'Asia/Ho_Chi_Minh') NOT NULL,
	created_by varchar(20),
	updated_at timestamp(3),
	updated_by varchar(20),
	CONSTRAINT trainee_fingerprints_pkey PRIMARY KEY (trainee_id, finger_index)
);

ALTER TABLE trainee_fingerprints DROP CONSTRAINT IF EXISTS fk_traineefp_trainee;
ALTER TABLE trainee_fingerprints ADD CONSTRAINT fk_traineefp_trainee
	FOREIGN KEY (trainee_id) REFERENCES trainees (id) ON DELETE CASCADE;
ALTER TABLE trainee_fingerprints DROP CONSTRAINT IF EXISTS fk_traineefp_device;
ALTER TABLE trainee_fingerprints ADD CONSTRAINT fk_traineefp_device
	FOREIGN KEY (source_device_id) REFERENCES attendance_devices (id) ON DELETE SET NULL;
ALTER TABLE trainee_fingerprints DROP CONSTRAINT IF EXISTS chk_traineefp_finger;
ALTER TABLE trainee_fingerprints ADD CONSTRAINT chk_traineefp_finger
	CHECK (finger_index BETWEEN 0 AND 9);

-- Điểm danh bằng máy chấm công
ALTER TABLE attendance DROP CONSTRAINT IF EXISTS chk_attendance_method;
ALTER TABLE attendance ADD CONSTRAINT chk_attendance_method
	CHECK (method IN ('qr', 'manual', 'device'));

COMMENT ON TABLE attendance_devices IS
	'Máy chấm công vân tay (ADMS/iclock) — nhận diện theo số serial; pending = chờ quản trị duyệt';
COMMENT ON TABLE attendance_punches IS
	'Lượt chấm thô từ máy chấm công (giờ UTC) + kết quả ghép vào buổi học';
COMMENT ON TABLE attendance_device_commands IS
	'Hàng đợi lệnh gửi xuống máy chấm công (máy tự hỏi qua /iclock/getrequest)';
COMMENT ON TABLE attendance_device_users IS
	'Học viên server đã gửi xuống từng máy chấm công';
COMMENT ON TABLE trainee_fingerprints IS
	'Mẫu vân tay học viên (mã hóa AES-GCM, utils/secretBox) để đồng bộ giữa các máy chấm công';
